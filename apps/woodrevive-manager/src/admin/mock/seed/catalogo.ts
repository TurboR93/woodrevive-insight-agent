/**
 * Catalogo articoli.
 *
 * Copre quello che Wood Revive compra e rivende: tavole (15–80 mm), perlinati
 * con incastro maschio-femmina, pannelli a 3 strati, lamelle (5–8 mm),
 * travature squadrate e tonde, pavimenti, rivestimenti e arredi. Tutto arriva
 * dal fornitore già pronto: nel catalogo non c'è nessun servizio, perché
 * nessun servizio viene eseguito.
 *
 * Ogni articolo porta due prezzi. `prezzo_acquisto_cents` è quanto costa
 * comprarlo, `prezzo_listino_cents` quanto si rivende: la distanza fra i due è
 * il mestiere. I margini stanno fra il 35% e il 41% sul prezzo di vendita,
 * più stretti sui prodotti da rivenditore e più larghi sui perlinati, dove il
 * volume di acquisto è alto.
 *
 * Nota su `mc_per_unita_milli`: per un articolo venduto a m², i metri cubi per
 * unità coincidono numericamente con lo spessore in mm (30 mm → 0,030 m³/m² →
 * 30 millesimi). Per le travature si calcola dalla sezione. Serve a confrontare
 * un'offerta quotata a metri cubi con un listino a metri quadri: senza, i due
 * prezzi non si possono nemmeno mettere accanto.
 *
 * Giacenze, costo medio e impegnato NON stanno qui: li ricalcola
 * `ricalcolaDerivati()` dai movimenti. Qui sono zero per costruzione.
 */

import type { Articolo } from '../../domain'
import type { Seme } from './comuni'
import { codice, mesiFa, tracce } from './comuni'

type SemeArticolo = Omit<
  Seme<Articolo>,
  | 'id'
  | 'codice'
  | 'created_at'
  | 'updated_at'
  | 'giacenza_milli'
  | 'impegnato_milli'
  | 'costo_medio_cents'
  | 'natura'
  | 'gestione_magazzino'
> & {
  natura?: Articolo['natura']
  gestione_magazzino?: boolean
}

function art(n: number, seme: SemeArticolo): Seme<Articolo> {
  return {
    id: `art-${String(n).padStart(2, '0')}`,
    codice: codice('ART', n),
    giacenza_milli: 0,
    impegnato_milli: 0,
    costo_medio_cents: 0,
    // Il catalogo dimostrativo è tutto legno che si tiene in magazzino: nessun
    // servizio, nessuna spesa da riaddebitare. È la premessa del dominio, e i
    // due campi sono qui perché si veda, non perché varino.
    natura: 'merce',
    gestione_magazzino: true,
    ...seme,
    ...tracce(mesiFa(24)),
  }
}

